#!/usr/bin/env python3
"""Settings search index: every setting's title, by section, read from
SettingsPanel.svelte — so the search finds "Night mode" or "Blur explicit
photos", not only section names. Writes ui/src/lib/settingsIndex.ts.

  python3 tools/settings_index.py          # write
  python3 tools/settings_index.py --check  # CI: fail if it's out of date
"""
import json, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent / "crates/aqua-client-ui/ui/src/lib"
SRC = ROOT / "components/SettingsPanel.svelte"
OUT = ROOT / "settingsIndex.ts"

src = SRC.read_text(encoding="utf-8")
parts = re.split(r'\n      \{#if section === "([a-z_-]+)"\}', src)
index = []
seen = set()
for i in range(1, len(parts), 2):
    sec, body = parts[i], parts[i + 1]
    # Titles of rows and groups (not the long explanations).
    for kind, text in re.findall(r'class="(label|tr-title|row-label)">\{\$t\("([^"\\]{2,80})"', body):
        key = (sec, text)
        if key in seen:
            continue
        seen.add(key)
        index.append([sec, text])

body = "// Generated by tools/settings_index.py from SettingsPanel.svelte — don't edit.\n" \
       "/** [section, setting title] — the settings search looks inside sections too. */\n" \
       "export const SETTINGS_INDEX: [string, string][] = " + json.dumps(index, ensure_ascii=False, indent=0).replace("\n", "") + ";\n"

if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != body:
        sys.exit("settingsIndex.ts is out of date: run python3 tools/settings_index.py")
    print(f"settings index ok ({len(index)} entries)")
else:
    OUT.write_text(body, encoding="utf-8")
    print(f"{OUT}: {len(index)} entries")
